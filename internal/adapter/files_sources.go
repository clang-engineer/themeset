package adapter

// Registered official theme source URLs and asset paths. The tool adapters
// validate downloaded data before changing application settings.
// Official Rosé Pine Main sources; downloads always use the current main branch.
type rosePineAsset struct {
	url string
}

func rosePineRecipe(id string) (rosePineAsset, bool) {
	var repo, file string
	switch id {
	case "starship":
		repo, file = "starship", "rose-pine.toml"
	case "fzf":
		repo, file = "fzf", "dist/rose-pine.sh"
	case "lazygit":
		repo, file = "lazygit", "themes/rose-pine.yml"
	case "atuin":
		repo, file = "atuin", "dist/rose-pine.toml"
	case "eza":
		repo, file = "eza", "dist/rose-pine.yml"
	case "btop":
		repo, file = "btop", "rose-pine.theme"
	default:
		return rosePineAsset{}, false
	}
	return rosePineAsset{"https://raw.githubusercontent.com/rose-pine/" + repo + "/main/" + file}, true
}

